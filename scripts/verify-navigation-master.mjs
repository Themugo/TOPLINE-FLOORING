import { readFileSync } from 'node:fs';
const r = (p) => readFileSync(p, 'utf8');
const header = r('src/components/layout/Header.tsx');
const footer = r('src/components/layout/Footer.tsx');
const app = r('src/App.tsx');
const nf = r('src/pages/not-found.tsx');
const hooks = r('src/hooks/use-data.ts');
const bar = r('src/components/layout/MobileActionBar.tsx');
const checks = [];
const check = (name, pass) => checks.push({ name, pass: Boolean(pass) });
check('Active-route families live in one shared helper', /isRouteActive/.test(r('src/lib/nav-active.ts')) && /isRouteActive/.test(header) && /isRouteActive/.test(bar));
check('External/new-tab links are safe and announced', /noopener noreferrer/.test(r('src/components/layout/NavAnchor.tsx')) && /opens in a new tab/.test(r('src/components/layout/NavAnchor.tsx')));
check('Header and footer use NavAnchor for CMS links', /NavAnchor/.test(header) && /NavAnchor/.test(footer));
check('Company pages are reachable from header and footer', /\/about/.test(header) && /\/industries/.test(footer) && /\/faq/.test(footer) && /\/market/.test(footer));
check('Footer services link to their own pages', /\/service\/\$\{service\.slug\}/.test(footer));
check('Footer staff link is demoted', /Staff sign in/.test(footer) && !/Admin Portal/.test(footer));
check('Menu location alias (main→header) is honoured', /\['header', 'main'\]/.test(hooks));
check('Router restores anchors, focus and announces routes', /route-announcer/.test(app) && /main-content/.test(app) && /scrollIntoView/.test(app));
check('404 offers helpful destinations', /Helpful pages/.test(nf));
for (const c of checks) console.log(`${c.pass ? 'PASS' : 'FAIL'} ${c.name}`);
console.log(`\nNavigation master: ${checks.filter((c) => c.pass).length}/${checks.length} passed.`);
if (checks.some((c) => !c.pass)) process.exitCode = 1;
