import fs from "node:fs";
import path from "node:path";
const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root,p),"utf8");
const checks=[];
function check(name, ok, detail="") { checks.push({name,passed:Boolean(ok),detail}); }
const runbook=read("docs/BREVO-EMAIL-INTEGRATION-RUNBOOK.md");
const phase3=read("docs/PHASE_3_REAL_PRODUCTION_EMAIL.md");
const env=read(".env.example");
const worker=read("supabase/functions/deliver-communications/index.ts");
const readiness=read("supabase/functions/communication-provider-readiness/index.ts");
const webhook=read("supabase/functions/communication-provider-webhook/index.ts");
const migrationFiles=fs.readdirSync("supabase/migrations").filter(x=>x.endsWith(".sql"));
const allMigrations=migrationFiles.map(x=>read(path.join("supabase/migrations",x))).join("\n");
const authTemplates=fs.readdirSync("docs/email-templates").filter(x=>x.endsWith(".html"));
check("Brevo transactional API endpoint",worker.includes("api.brevo.com/v3/smtp/email"));
check("Brevo sender is server-side configuration",worker.includes('Deno.env.get("BREVO_SENDER_EMAIL")'));
check("Sender display name is configurable",worker.includes('Deno.env.get("BREVO_SENDER_NAME")'));
check("Reply-to fallback is present",worker.includes("item.reply_to || brevoReplyToEmail"));
check("Provider request timeout is bounded",worker.includes("PROVIDER_TIMEOUT_MS = 20_000"));
check("Provider response must be successful",worker.includes("if (!response.ok) throw new Error"));
check("Provider message identity is captured",worker.includes("parsed.messageId"));
check("Outbox attempt audit is recorded",worker.includes("record_communication_delivery_attempt_worker"));
check("Ambiguous delivery is not blindly retried",worker.includes('"uncertain"'));
check("Readiness requires Brevo credentials",readiness.includes('"BREVO_API_KEY", "BREVO_SENDER_EMAIL"'));
check("Readiness endpoint authenticates worker",readiness.includes("x-topline-worker-secret"));
check("Readiness does not disclose credentials",readiness.includes("credentials_exposed: false"));
check("Provider webhook has authentication",/constantTimeEqual|COMMUNICATION_WEBHOOK_SECRET/.test(webhook));
check("Provider webhook stores durable events",webhook.includes("record_provider_delivery_event_worker"));
check("Bounce and complaint suppression is implemented",allMigrations.includes("communication_suppressions"));
check("Suppressed recipients are prevented from sending",worker.includes("communication_suppressions"));
check("Marketing subscribe checks newer unsubscribe",worker.includes("newerUnsubscribe"));
check("Marketing sync requires configured list ID",worker.includes("BREVO_MARKETING_LIST_ID"));
check("Public environment has no provider secret",!/^VITE_.*(?:BREVO_API_KEY|SMTP|WORKER_SECRET)/mi.test(env));
check("Runbook requires SPF",/SPF/i.test(runbook));
check("Runbook requires DKIM",/DKIM/i.test(runbook));
check("Runbook requires DMARC",/DMARC/i.test(runbook));
check("Runbook separates Auth SMTP credentials",runbook.includes("SMTP password") || runbook.includes("SMTP login"));
check("Domain records must not be guessed",phase3.includes("Never publish guessed SPF/DKIM values"));
check("Auth templates are present",["confirm-signup.html","reset-password.html","magic-link.html"].every(x=>authTemplates.includes(x)));

const dnsAudit=read("scripts/audit-g13-email-dns.mjs");
const inboxValidator=read("scripts/verify-g13-inbox-evidence.mjs");
const g13Runbook=read("docs/G-13-EMAIL-DELIVERABILITY-UAT-RUNBOOK-2026-11-07.md");
const pkg=JSON.parse(read("package.json"));
const workflow=read(".github/workflows/ci.yml");
check("DNS audit queries Cloudflare and Google",dnsAudit.includes("cloudflare-dns.com/dns-query") && dnsAudit.includes("dns.google/resolve"));
check("DKIM selector is operator-supplied, never guessed",dnsAudit.includes("TOPLINE_DKIM_SELECTOR") && dnsAudit.includes("SELECTOR_REQUIRED"));
check("DNS audit is read-only and emits evidence",dnsAudit.includes("dns-audit.json") && !/changeResourceRecord|updateDns|deleteDns/i.test(dnsAudit));
check("Inbox evidence requires SPF DKIM DMARC pass",["spf=pass","dkim=pass","dmarc=pass"].every(x=>inboxValidator.includes(x)));
check("Inbox evidence requires actual Inbox placement",inboxValidator.includes("toLowerCase() === 'inbox'"));
check("Runbook protects cPanel MX and one SPF record",g13Runbook.includes("preserve existing cPanel MX") && g13Runbook.includes("exactly one TXT record"));
check("Runbook requires real Authentication-Results headers",g13Runbook.includes("Authentication-Results"));
check("DNS audit npm command registered",pkg.scripts["audit:g13-email-dns"] === "node scripts/audit-g13-email-dns.mjs");
check("Inbox evidence npm command registered",pkg.scripts["verify:g13-inbox-evidence"] === "node scripts/verify-g13-inbox-evidence.mjs");
check("CI checks new evidence tooling syntax",workflow.includes("G-13 real DNS and inbox evidence tooling contract"));
const failed=checks.filter(x=>!x.passed);
console.log(JSON.stringify({check:"G-13 email deliverability source certification",passed:checks.length-failed.length,total:checks.length,failed,checks},null,2));
if(failed.length) process.exit(1);
