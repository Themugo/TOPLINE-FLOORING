import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const fail=m=>{throw new Error(m)};
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const cert=read('supabase/migrations/20261002210000_payment_provider_certification_activation_360.sql');
const init=read('supabase/functions/payment-initiate/index.ts');
const portal=read('src/pages/portal.tsx');
const gateway=read('scripts/verify-payment-gateway-customer-visibility-360.mjs');
if(!cert.includes("Production certification requires an evidence reference")) fail('Production certification evidence is not mandatory.');
if(!cert.includes('Production certification requires complete payment UAT evidence')) fail('Production certification UAT checklist is not enforced.');
if(!cert.includes('TO service_role')) fail('Provider release gate is not available to the server-side payment initiator.');
if(!init.includes("get_payment_provider_release_gate_360")) fail('Payment initiation does not enforce the production release gate.');
if(!init.includes('allowedBankKeys')) fail('Bank-transfer customer configuration is not allowlisted.');
if(!init.includes('payment ledger could not be updated')) fail('Provider acceptance is not fail-closed on ledger persistence failure.');
const callback=read('supabase/functions/payment-callback/index.ts');
if(!callback.includes('rawBody=await req.text()')) fail('Card callback signature verification does not use the raw request body.');
if(!callback.includes('merchantRequest&&tx.provider_reference!==merchantRequest')) fail('M-Pesa callback does not bind MerchantRequestID to the initiated transaction.');
if(!callback.includes("payment_attempts').update({status:'failed'")) fail('M-Pesa failure fallback does not close the payment attempt.');
if(portal.includes('idempotencyKey:`portal-order-payment:${selectedRecord.value.id}:${orderPaymentGatewayKey}`')) fail('Portal order Pay Now still reuses a deterministic retry key.');
if(portal.includes('idempotencyKey:`portal-invoice-payment:${selectedRecord.value.id}:${invoicePaymentGatewayKey}`')) fail('Portal invoice Pay Now still reuses a deterministic retry key.');
if(!gateway.includes("find(f=>f.startsWith('20261002190000_payment_gateway_customer_visibility_admin_control_360.sql'))")) fail('Gateway verifier still assumes its migration must be latest.');
console.log('Payment Audit 360: PASS');
